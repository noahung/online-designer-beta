import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const sourceRoot = path.join(root, 'src');
const outputPath = path.join(root, 'docs', 'repository-graph.md');
const extensions = ['.ts', '.tsx', '.js', '.jsx'];
const ignoredDirs = new Set(['node_modules', 'dist', 'docs', '.git']);

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith('.') || ignoredDirs.has(entry.name)) return [];
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(absolute);
    return extensions.includes(path.extname(entry.name)) ? [absolute] : [];
  });
}

function toPosix(relativePath) {
  return relativePath.split(path.sep).join('/');
}

function bucketFor(filePath) {
  const relative = toPosix(path.relative(sourceRoot, filePath));
  const parts = relative.split('/');
  if (parts.length === 1) return 'src root';
  if (parts[0] === 'components' && parts.length > 2) return `components/${parts[1]}`;
  return parts[0];
}

function resolveImport(fromFile, specifier, knownFiles) {
  if (!specifier.startsWith('.')) return null;

  const base = path.resolve(path.dirname(fromFile), specifier);
  const candidates = [
    base,
    ...extensions.map((extension) => `${base}${extension}`),
    ...extensions.map((extension) => path.join(base, `index${extension}`)),
  ];

  return candidates.find((candidate) => knownFiles.has(candidate)) ?? null;
}

function escapeMermaidId(label) {
  return label.replace(/[^a-zA-Z0-9_]/g, '_');
}

const files = walk(sourceRoot);
const knownFiles = new Set(files);
const importPattern = /(?:import\s+(?:[\s\S]*?\s+from\s+)?|export\s+[\s\S]*?\s+from\s+|import\s*\()\s*['"]([^'"]+)['"]/g;
const bucketCounts = new Map();
const edges = new Map();

for (const file of files) {
  const bucket = bucketFor(file);
  bucketCounts.set(bucket, (bucketCounts.get(bucket) ?? 0) + 1);

  const contents = fs.readFileSync(file, 'utf8');
  for (const match of contents.matchAll(importPattern)) {
    const resolved = resolveImport(file, match[1], knownFiles);
    if (!resolved) continue;

    const targetBucket = bucketFor(resolved);
    if (targetBucket === bucket) continue;

    const key = `${bucket} -> ${targetBucket}`;
    edges.set(key, (edges.get(key) ?? 0) + 1);
  }
}

const sortedBuckets = [...bucketCounts.entries()].sort(([a], [b]) => a.localeCompare(b));
const sortedEdges = [...edges.entries()].sort(([a], [b]) => a.localeCompare(b));

const mermaidLines = [
  'graph TD',
  ...sortedBuckets.map(([bucket, count]) => {
    const id = escapeMermaidId(bucket);
    return `  ${id}["${bucket}<br/>${count} files"]`;
  }),
  ...sortedEdges.map(([edge, count]) => {
    const [from, to] = edge.split(' -> ');
    return `  ${escapeMermaidId(from)} -->|${count}| ${escapeMermaidId(to)}`;
  }),
];

const routeGraph = [
  'graph TD',
  '  main["src/main.tsx"] --> app["src/App.tsx"]',
  '  app --> auth["AuthProvider"]',
  '  app --> toast["ToastProvider"]',
  '  app --> router["React Router"]',
  '  router --> publicApi["/api/forms"]',
  '  router --> publicForm["/form/:id"]',
  '  router --> admin["Admin routes"]',
  '  router --> shared["Shared authenticated routes"]',
  '  admin --> dashboard["Dashboard"]',
  '  admin --> clients["Clients"]',
  '  admin --> forms["Forms / FormBuilder / SinglePageFormBuilder"]',
  '  admin --> formResponses["FormResponses"]',
  '  admin --> settings["Settings"]',
  '  shared --> responses["Responses"]',
  '  shared --> responseDetail["ResponseDetail"]',
];

const topEdges = sortedEdges
  .sort(([, a], [, b]) => b - a)
  .slice(0, 12)
  .map(([edge, count]) => `| ${edge.replace(' -> ', ' | ')} | ${count} |`)
  .join('\n');

const markdown = `# Repository Graph

Generated by \`node tools/graphify.mjs\`.

## Source Module Graph

\`\`\`mermaid
${mermaidLines.join('\n')}
\`\`\`

## Runtime Route Graph

\`\`\`mermaid
${routeGraph.join('\n')}
\`\`\`

## Source Areas

| Area | Files |
| --- | ---: |
${sortedBuckets.map(([bucket, count]) => `| ${bucket} | ${count} |`).join('\n')}

## Strongest Internal Links

| From | To | Imports |
| --- | --- | ---: |
${topEdges || '| n/a | n/a | 0 |'}
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, markdown);
console.log(`Wrote ${path.relative(root, outputPath)}`);
